"""Command line entry point: process every video in one folder (non-recursive)."""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import shutil
import subprocess
import sys
import tempfile
from concurrent.futures import ThreadPoolExecutor
from dataclasses import asdict, dataclass
from pathlib import Path
from typing import Callable

from . import __version__
from .extract import extract_srts
from .merge import MergeOptions, build_dual
from .probe import SelectionError, parse_media_info, run_ffprobe, select_tracks

VIDEO_EXTS = {".mkv", ".mp4", ".m4v"}
OUTPUT_SUFFIX = ".zh.dual.ass"
MARKER = "; dualsubs-zh:"
FORMAT_VERSION = 1


@dataclass
class Deps:
    """External calls, swappable in tests."""

    probe: Callable[[Path], dict] = run_ffprobe
    extract: Callable[[Path, list[int]], dict[int, str]] = extract_srts


def output_path(video: Path) -> Path:
    return video.with_name(video.stem + OUTPUT_SUFFIX)


def source_hash(video: Path, en_index: int, zh_index: int, options: MergeOptions) -> str:
    st = video.stat()
    payload = json.dumps(
        {
            "v": FORMAT_VERSION,
            "size": st.st_size,
            "mtime": int(st.st_mtime),
            "en": en_index,
            "zh": zh_index,
            "opts": asdict(options),
        },
        sort_keys=True,
    )
    return hashlib.sha256(payload.encode()).hexdigest()[:16]


def read_marker(path: Path) -> str | None:
    """Return the hash in our header, or None if the file isn't ours."""
    try:
        with path.open(encoding="utf-8-sig") as f:
            for _, line in zip(range(10), f):
                if line.startswith(MARKER):
                    for part in line[len(MARKER):].split():
                        if part.startswith("src="):
                            return part[4:]
    except OSError:
        return None
    return None


def render(ass_text: str, digest: str) -> str:
    header = f"{MARKER} v{FORMAT_VERSION} src={digest} (generated by dualsubs-zh {__version__})"
    return ass_text.replace("[Script Info]", "[Script Info]\n" + header, 1)


def write_atomic(path: Path, text: str) -> None:
    fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=".dualsubs-", suffix=".tmp")
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as f:
            f.write(text)
        os.replace(tmp, path)
    except BaseException:
        Path(tmp).unlink(missing_ok=True)
        raise


def process_video(video: Path, options: MergeOptions, force: bool, dry_run: bool, deps: Deps) -> tuple[str, str]:
    """Return (status, detail). Status is created/skipped/error."""
    info = parse_media_info(deps.probe(video))
    try:
        sel = select_tracks(info)
    except SelectionError as e:
        return "skipped", str(e)

    out = output_path(video)
    digest = source_hash(video, sel.english.index, sel.chinese.index, options)
    if out.exists():
        existing = read_marker(out)
        if existing == digest and not force:
            return "skipped", "up-to-date"
        if existing is None and not force:
            return "skipped", f"{out.name} exists and was not made by dualsubs-zh (use --force)"
        if existing != digest and not force:
            return "skipped", "outdated (source or options changed; use --force to regenerate)"

    detail = f"en {sel.english.label} + zh {sel.chinese.label}"
    if sel.warnings:
        detail += " [" + "; ".join(sel.warnings) + "]"
    if dry_run:
        return "would create", detail

    texts = deps.extract(video, [sel.english.index, sel.chinese.index])
    subs = build_dual(
        texts[sel.english.index],
        texts[sel.chinese.index],
        info.width,
        info.height,
        options,
    )
    write_atomic(out, render(subs.to_string("ass"), digest))
    return "created", detail


DEFAULT_JOBS = min(4, os.cpu_count() or 1)


def positive_int(value: str) -> int:
    n = int(value)
    if n < 1:
        raise argparse.ArgumentTypeError("must be >= 1")
    return n


def parse_args(argv: list[str] | None) -> argparse.Namespace:
    p = argparse.ArgumentParser(
        prog="dualsubs-zh",
        description="Write <video>.zh.dual.ass sidecars combining English and Simplified Chinese subtitles.",
    )
    p.add_argument("folder", type=Path, help="folder of videos (not recursive)")
    p.add_argument("--zh-position", choices=["top", "bottom"], default="top",
                   help="Chinese at top of screen, or stacked above English at bottom (default: top)")
    p.add_argument("--font", default=MergeOptions.zh_font, help=f"Chinese font name (default: {MergeOptions.zh_font})")
    p.add_argument("--font-scale", type=float, default=1.0, help="multiply default text size (default: 1.0)")
    p.add_argument("--force", action="store_true", help="overwrite existing/outdated sidecars")
    p.add_argument("--jobs", "-j", type=positive_int, default=DEFAULT_JOBS,
                   help=f"videos to process in parallel (default: {DEFAULT_JOBS})")
    p.add_argument("--dry-run", action="store_true", help="show what would happen without writing")
    p.add_argument("--version", action="version", version=f"%(prog)s {__version__}")
    return p.parse_args(argv)


def main(argv: list[str] | None = None, deps: Deps | None = None) -> int:
    args = parse_args(argv)
    if deps is None:
        missing = [t for t in ("ffmpeg", "ffprobe") if shutil.which(t) is None]
        if missing:
            print(f"error: {', '.join(missing)} not found on PATH", file=sys.stderr)
            return 2
        deps = Deps()
    if not args.folder.is_dir():
        print(f"error: {args.folder} is not a directory", file=sys.stderr)
        return 2

    options = MergeOptions(zh_position=args.zh_position, zh_font=args.font, font_scale=args.font_scale)
    videos = sorted(p for p in args.folder.iterdir() if p.is_file() and p.suffix.lower() in VIDEO_EXTS)
    def run_one(video: Path) -> tuple[str, str]:
        try:
            return process_video(video, options, args.force, args.dry_run, deps)
        except (subprocess.CalledProcessError, OSError, ValueError) as e:
            return "error", str(e)

    # Threads are enough: the heavy lifting happens in ffmpeg subprocesses.
    # map() yields in input order, so output stays sorted by filename.
    counts: dict[str, int] = {}
    with ThreadPoolExecutor(max_workers=args.jobs) as pool:
        for video, (status, detail) in zip(videos, pool.map(run_one, videos)):
            counts[status] = counts.get(status, 0) + 1
            print(f"{status:>12}  {video.name}: {detail}", flush=True)

    summary = ", ".join(f"{n} {s}" for s, n in sorted(counts.items())) or "no videos found"
    print(f"\n{summary}")
    return 1 if counts.get("error") else 0


if __name__ == "__main__":
    sys.exit(main())
